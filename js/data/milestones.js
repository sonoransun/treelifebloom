/**
 * The milestone to show at timeMa, as { ...milestone, progress } (progress 0 at the window's
 * leading, older edge → 1 at its trailing edge), or null when none is active.
 * When windows overlap, the highest `priority` wins, then the one that started most recently.
 */
export function getActiveMilestone(timeMa) {
  let best = null;
  let bestPriority = -Infinity;
  let bestStart = Infinity;
  for (const m of milestones) {
    const start = m.timeMa + m.durationMa / 2;
    const end = m.timeMa - m.durationMa / 2;
    if (timeMa > start || timeMa < end) continue;
    const priority = m.priority || 0;
    if (priority > bestPriority || (priority === bestPriority && start < bestStart)) {
      best = m;
      bestPriority = priority;
      bestStart = start;
    }
  }
  if (!best) return null;
  return { ...best, progress: (bestStart - timeMa) / best.durationMa };
}
