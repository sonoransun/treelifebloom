// Narrative milestones — the beats of the story that are not mass extinctions: a toast at the
// top of the stage, a dot on the timeline, and (when it has a `location`) a place on the map.
//
// Entry:
//   id          stable snake_case key
//   timeMa      the date shown with the toast and marked on the timeline. For an interval
//               (a glaciation, a radiation) it is the midpoint.
//   durationMa  trigger window, timeMa ± durationMa/2: the milestone is "active" while the
//               clock is inside it. The toast keeps itself readable for longer than a short
//               window lasts, so windows are sized for pacing, not for reading time.
//   name        toast title
//   description ≤ 240 characters, present tense, one idea; contested claims are hedged
//   category    'cosmic' | 'geological' | 'climatic' | 'biological' | 'cultural' | 'crisis'
//               (see MILESTONE_CATEGORIES; icons and colour families key on it)
//   color       a shade of the category's hue. The six hues are steps of the same palette as
//               LIFE_GROUPS in config.js; in the order of MILESTONE_CATEGORIES they pass the
//               dataviz palette validator on the app's dark surface. No six hues are pairwise
//               safe for every kind of colour vision, so colour must never be the only cue:
//               show the category icon or label with it.
//   priority    optional, default 0: 2 = headline, 1 = notable. Breaks ties between
//               overlapping windows and decides what a crowded toast queue keeps.
//   location    optional { plateId, lon, lat, name }: the MODERN coordinates of the place the
//               description points at (the engine carries the point back on its plate)
//   crisisId    optional: id of the entry in `crises` (extinctions.js) this toast narrates —
//               the two are one event and share one timeline marker (the timeline pairs a
//               'crisis' toast with the crisis of the same id, or else the one it overlaps)
//
// Order: oldest first. Windows never touch a mass-extinction window (the extinction card owns
// those seconds), and no two windows open within a second of playback of each other. Spacing
// follows the screen-time scale (engine/timeScale.js): roughly one toast every 5–8 s at 1×,
// denser only where history is (the opening, the Pliocene, the last 12,000 years).
// Sources for every entry are listed in docs/data-sources.md.

